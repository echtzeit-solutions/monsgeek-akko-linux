#!/usr/bin/env python3
"""Generate udev/99-monsgeek-rebrands.rules from data/devices.json.

udev/99-monsgeek.rules opens every hidraw node under the MonsGeek VID 0x3151.
Rebranded boards (Akko 0x38EE and others) use their own VIDs, which also cover
unrelated products, so they get one rule per VID:PID listed in the database
instead of a rule per VID.

Run by scripts/update-device-db.sh after each database update.
"""

import json
import sys
from pathlib import Path

MONSGEEK_VID = 0x3151
# Same keyboard filter as the driver's discovery registration
# (iot_driver_linux/src/profile/registry.rs): the database also lists mice and
# receivers, and negative ids are placeholders.
KEYBOARD_TYPES = {"keyboard", "hitBoxKeyboard"}
# udev only: a PID under Apple's VID is shared with genuine Apple keyboards (an
# Akko Mac edition reuses 05ac:024f), and opening every such hidraw node to all
# users is not acceptable. The driver still finds the board when run as root.
EXCLUDED_VIDS = {0x05AC}

ROOT = Path(__file__).resolve().parent.parent
DEVICES = ROOT / "data" / "devices.json"
RULES = ROOT / "udev" / "99-monsgeek-rebrands.rules"

HEADER = """\
# Rebranded MonsGeek-protocol keyboards under other vendor IDs.
# GENERATED by scripts/generate-udev-rules.py from data/devices.json; do not edit.
# Install alongside 99-monsgeek.rules (make install-udev).
"""


def load_devices(path: Path) -> list[dict]:
    data = json.loads(path.read_text())
    devices = data.get("devices", data) if isinstance(data, dict) else data
    return list(devices.values()) if isinstance(devices, dict) else devices


def main() -> int:
    names: dict[tuple[int, int], set[str]] = {}
    for d in load_devices(DEVICES):
        vid, pid = d["vid"], d["pid"]
        if d["id"] < 0 or d.get("type") not in KEYBOARD_TYPES:
            continue
        if vid != MONSGEEK_VID and vid not in EXCLUDED_VIDS:
            names.setdefault((vid, pid), set()).add(d.get("displayName") or d["name"])

    lines = [HEADER]
    for (vid, pid), models in sorted(names.items()):
        lines.append(f"# {', '.join(sorted(models))}")
        lines.append(
            f'SUBSYSTEM=="hidraw", ATTRS{{idVendor}}=="{vid:04x}", '
            f'ATTRS{{idProduct}}=="{pid:04x}", MODE="0666"'
        )
    RULES.write_text("\n".join(lines) + "\n")
    print(f"Wrote {len(names)} VID:PID rules to {RULES.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
